function [K1_nn,K2_nn,K3_nn,K4_nn] = Kup2l(dtn, N1,N3,r1star,r2star,r3star,r4star,r12star,r34star,F1,F3,U1_n,U2_n,U3_n,U4_n,U1star,U2star,U3star,U4star,B12_n,B34_n,B12starmatcT,B34starmatcT,Btil12,Btil34)

 %Update Eqns for the leaf bases for leaf bases of 2 laplacian 4d heat eqn

 K1_nn = sylvesterf( (speye(N1)-dtn*F1), ...
        -dtn*( kron( B34starmatcT'*kron( speye(r4star), U3star'*F3'*U3star )*B34starmatcT,speye(r2star) ) ), ...
            U1_n * tens2mat(Btil12,1) * kron( tens2mat(B34_n,3)*kron(U4_n'*U4star,U3_n'*U3star)*B34starmatcT, U2_n'*U2star)  );
        
 K2_nn = U2_n*tens2mat(Btil12,2)*kron(  tens2mat(B34_n,3)*kron(U4_n'*U4star,U3_n'*U3star)*B34starmatcT...
            , U1_n'*U1star) / ... 
             ( speye(r34star*r1star) - ( kron(speye(r34star), dtn*U1star'*F1'*U1star) + ...
            kron( B34starmatcT'*kron( speye(r4star), dtn*U3star'* F3'* U3star)* B34starmatcT ,speye(r1star)) ) );
                                                     
 K3_nn = sylvesterf( (speye(N3)-dtn*F3), ...
        -dtn*( kron( B12starmatcT'*kron( speye(r2star), U1star'*F1'*U1star )*B12starmatcT,speye(r4star) ) ), ...
            U3_n * tens2mat(Btil34,1) * kron( tens2mat(B12_n,3)*kron(U2_n'*U2star,U1_n'*U1star)*B12starmatcT, U4_n'*U4star)  );

 K4_nn = U4_n*tens2mat(Btil34,2)*kron( tens2mat(B12_n,3)*kron(U2_n'*U2star,U1_n'*U1star)*B12starmatcT...
            , U3_n'*U3star)  / ... 
            ( speye(r12star*r3star) - ( kron(speye(r12star), dtn*U3star'*F3'*U3star) + ...
            kron( B12starmatcT'*kron( speye(r2star), dtn*U1star'* F1'* U1star)* B12starmatcT ,speye(r3star)) ) ) ;

end